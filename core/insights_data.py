def get_articles(category_slug=None):
    """Filter articles by category slug or return all."""
    if not category_slug or category_slug == 'all':
        return ARTICLES
    return [a for a in ARTICLES if a['category_slug'] == category_slug]


def get_featured_article():
    """Retrieve the primary featured deep dive article."""
    for article in ARTICLES:
        if article.get('is_featured'):
            return article
    return ARTICLES[0]
